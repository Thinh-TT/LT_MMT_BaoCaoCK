    /**
     * Phuong thuc dung Server an toan va giai phong Registry port.
     */
    private void stopServer() {
        try {
            if (registry != null) {
                try {
                    registry.unbind(RMIServer.SERVICE_NAME);
                    appendLog(String.format("-> [RMI Server] Đã hủy đăng ký (unbind) '%s' khỏi Registry.", RMIServer.SERVICE_NAME));
                } catch (Exception ignored) {}
            }

            if (helloService != null) {
                try {
                    UnicastRemoteObject.unexportObject(helloService, true);
                    appendLog("-> [RMI Server] Đã unexport Remote Object HelloImpl.");
                } catch (Exception ignored) {}
                helloService = null;
            }

            if (registry != null && isRegistryCreatedLocally) {
                try {
                    UnicastRemoteObject.unexportObject(registry, true);
                    appendLog("-> [RMI Server] Đã đóng RMI Registry và giải phóng cổng TCP.");
                } catch (Exception ignored) {}
                registry = null;
            }

            appendLog("-> [RMI Server] Server đã dừng hoàn toàn.\n");

        } catch (Exception e) {
            appendLog("[Lỗi khi dừng] " + e.getMessage());
        } finally {
            btnStart.setEnabled(true);
            txtPort.setEnabled(true);
            btnStop.setEnabled(false);
            progressBar.setIndeterminate(false);
            progressBar.setString("Đã dừng (Stopped)");
            lblStatus.setText("Trạng thái: Đã dừng");
        }
    }

