    /**
     * Xu ly su kien nut Start Registry.
     */
    private void btnStartActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStartActionPerformed
        int port;

        try {
            port = Integer.parseInt(txtPort.getText().trim());
            if (port <= 1024 || port > 65535) {
                JOptionPane.showMessageDialog(this, "Vui lòng nhập Port hợp lệ (1025 - 65535)!", "Lỗi", JOptionPane.ERROR_MESSAGE);
                return;
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Port phải là một số nguyên!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return;
        }

        btnStart.setEnabled(false);
        txtPort.setEnabled(false);
        btnStop.setEnabled(true);

        progressBar.setIndeterminate(true);
        progressBar.setString(String.format("Starting RMI Registry on port %d...", port));
        lblStatus.setText(String.format("Trạng thái: Đang khởi tạo Registry trên cổng %d...", port));

        SwingWorker<Void, Void> worker = new SwingWorker<Void, Void>() {
            @Override
            protected Void doInBackground() throws Exception {
                try {
                    registry = LocateRegistry.createRegistry(port);
                    isRegistryCreatedLocally = true;
                    appendLog(String.format("-> [RMI Server] Đã tạo mới RMI Registry trên cổng TCP: %d", port));
                } catch (RemoteException e) {
                    registry = LocateRegistry.getRegistry(port);
                    isRegistryCreatedLocally = false;
                    appendLog(String.format("-> [RMI Server] Đã kết nối tới RMI Registry hiện có trên cổng TCP: %d", port));
                }

                // Khoi tao Remote Object kem listener
                helloService = new HelloImpl(new RMIServerListener() {
                    @Override
                    public void onLog(String message) {
                        SwingUtilities.invokeLater(() -> appendLog(message));
                    }

                    @Override
                    public void onRegistryStarted(int p) {
                    }

                    @Override
                    public void onServiceBound(String serviceName) {
                    }

                    @Override
                    public void onRemoteCall(String clientHost, String paramName, String result) {
                        SwingUtilities.invokeLater(() -> {
                            callCounter++;
                            String timeStr = LocalTime.now().format(timeFormatter);

                            // In pipeline 3 buoc theo dung dac ta bao cao cuoi ky
                            appendLog("\n-------------------------------------------------------------");
                            appendLog(String.format("[Lượt #%d] Remote Call từ Client [%s]: sayHello(\"%s\")", callCounter, clientHost, paramName));
                            appendLog(String.format("-> [Buoc 1: Stub]     Marshalling tham so: \"%s\"", paramName));
                            appendLog("-> [Buoc 2: Skeleton] Unmarshalling thanh cong");
                            appendLog(String.format("-> [Buoc 3: Server]   HelloImpl.sayHello() thuc thi -> \"%s\"", result));
                            appendLog("==> Thu tu: Stub -> Skeleton -> HelloImpl.sayHello()");
                            appendLog("-------------------------------------------------------------");

                            // Cap nhat vao JTable
                            DefaultTableModel model = (DefaultTableModel) tblCalls.getModel();
                            model.addRow(new Object[]{callCounter, timeStr, clientHost, paramName, result});

                            progressBar.setString(String.format("Đã phục vụ %d lượt gọi RMI", callCounter));
                        });
                    }

                    @Override
                    public void onServiceUnbound(String serviceName) {
                    }

                    @Override
                    public void onServerStopped() {
                    }
                });

                // Dang ky service vao Registry
                registry.rebind(RMIServer.SERVICE_NAME, helloService);
                appendLog(String.format("-> [RMI Server] Đã đăng ký (bind) service '%s' thành công vào Registry.", RMIServer.SERVICE_NAME));
                appendLog("-> [RMI Server] Sẵn sàng nhận lời gọi phương thức từ xa (Waiting for remote calls...)\n");

                return null;
            }

            @Override
            protected void done() {
                try {
                    get();
                    lblStatus.setText(String.format("Trạng thái: Đang lắng nghe RMI trên cổng %d", port));
                    progressBar.setIndeterminate(false);
                    progressBar.setString("Waiting for remote calls...");
                } catch (Exception e) {
                    String err = e.getCause() != null ? e.getCause().getMessage() : e.getMessage();
                    JOptionPane.showMessageDialog(ServerForm.this, "Lỗi khởi động RMI Server: " + err, "Lỗi", JOptionPane.ERROR_MESSAGE);
                    stopServer();
                }
            }
        };

        worker.execute();
    }//GEN-LAST:event_btnStartActionPerformed

